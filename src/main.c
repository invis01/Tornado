#include <stdio.h>
#include "network.h"

#define PORT 7777
#define SERVER_ADDR "connect.playvortex.io"
#define FIXEDPAYLOAD 0x6, 0x0, 0x0, 0x0, 0x40, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x0, 0x39, 0x61, 0x31, 0x65, 0x34, 0x37, 0x37, 0x62, 0x62, 0x64, 0x61, 0x34, 0x38, 0x38, 0x37, 0x66, 0x39, 0x37, 0x61, 0x33, 0x31, 0x66, 0x65, 0x35, 0x30, 0x33, 0x39, 0x34, 0x65, 0x35, 0x30, 0x31, 0x30, 0x30, 0x66, 0x39, 0x61, 0x62, 0x61, 0x63, 0x35, 0x35, 0x31, 0x38, 0x63, 0x33, 0x39, 0x66, 0x37, 0x38, 0x30, 0x65, 0x35, 0x66, 0x65, 0x38, 0x66, 0x37, 0x35, 0x35, 0x39, 0x64, 0x35, 0x34

int main() {
    char packet_buffer[256];
    int sock;
    sock = init_socket(SERVER_ADDR, PORT);

    static const unsigned char payload[] = {FIXEDPAYLOAD};

    send_packet(sock, payload, sizeof(payload));

    ssize_t responselength = receive_packet(sock, packet_buffer, sizeof(packet_buffer));

    if (responselength > 0) {
        printf("Received %zd bytes: ", responselength);
        for (ssize_t i = 0; i < responselength; i++) {
            printf("0x%02x ", packet_buffer[i]);
        }
        printf("\n");
    } else if (responselength < 0) {
        perror("Response error!");
    }
    else {
        printf("No response...");
    }

    return 1;
}
